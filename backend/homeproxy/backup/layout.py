"""What a backup holds, and the limits on an uploaded one."""

from typing import Final

INCLUDED: Final = ("config", "secrets", "certs", "acme", "tls", "history", "audit")
"""The top-level entries of `/data` in an archive. A restore takes only these."""

EXCLUDED: Final = (
    "generated",  # rebuilt by the first apply
    "generated.prev",
    "releases",  # rebuilt by the first apply
    "state",  # metrics, logs and caches
    "pending",  # a restore starts with nothing staged
    "migration-backups",  # old copies, which also hold secrets
    "geoip",  # downloaded again
    "crowdsec",  # generated by an apply
    "store.lock",
)
"""Top-level entries of `/data` that an archive leaves out. A new entry of `/data` must be in this
list or in `INCLUDED`; a test checks the layout that `image/scripts/init-data` makes."""

MAX_UPLOAD_BYTES: Final = 100 * 1024 * 1024
"""The largest upload. A real `/data` is mostly YAML, certificates and history: a few MiB."""
MAX_EXTRACTED_BYTES: Final = 500 * 1024 * 1024
"""The most bytes the members of an upload may hold, by their declared sizes."""
MAX_MEMBERS: Final = 20_000
"""The most members of an upload. Fifty snapshots of a large config stay far below this."""
